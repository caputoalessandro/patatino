import { serve, browser, offlineFonts } from "./comune.mjs";
const { server, url } = await serve("/home/user/patatino"); const b = await browser();
const ctx = await b.newContext({viewport:{width:360, height:780}, isMobile:true, hasTouch:true}); await offlineFonts(ctx);
const p = await ctx.newPage(); const errs = []; p.on("pageerror", e => errs.push(e.message));
const fails = []; const ok = (c, m) => { console.log((c ? "OK  " : "FAIL") + " " + m); if(!c) fails.push(m); };
await p.goto(url); await p.waitForTimeout(400);
ok(await p.locator(".unit").count() === 30, "30 unità nel percorso");
ok(await p.locator(".lock, .glock, .locked").count() === 0, "nessun lucchetto");
const g = p.locator(".grp").nth(5); await g.locator(".grp-h").click(); await p.waitForTimeout(150);
await g.locator(".unit").last().click(); await p.waitForTimeout(300);
ok((await p.locator(".note").innerText()).length > 200, "unità 30 aperta con la spiegazione");
await p.goto(url); await p.waitForTimeout(300); await p.locator(".tab").nth(2).click(); await p.waitForTimeout(250);
await p.locator(".deck").first().click(); await p.waitForTimeout(250);
ok(await p.evaluate(() => history.state.s) === "quiz", "Costruisci la frase funziona");
await p.goto(url); await p.waitForTimeout(300); await p.locator(".tab").nth(1).click(); await p.waitForTimeout(250);
ok(await p.locator(".deck").count() === 18, "18 mazzi di flashcard liberi");
await p.goto(url); await p.waitForTimeout(300); await p.click("#vox"); await p.waitForTimeout(250);
const t = await p.locator(".settings-scr").innerText();
ok(!/Colori|Licenza|Sostieni|donazion/i.test(t) && /I tuoi dati/.test(t) && /Installa/.test(t), "impostazioni: niente colori né licenza, sì backup e installazione");
ok(await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--bg").trim().toUpperCase()) === "#F5D130", "colore classico");
await p.screenshot({path:"/tmp/patatino-test/shots3/pubblica-settings.png", fullPage:true});
ok(!errs.length, "nessun errore JS " + errs.join(" | "));
await b.close(); server.close(); process.exit(fails.length ? 1 : 0);
